/// Spacing and radii from Figma.
abstract final class AppSpacing {
  static const double xxs = 4;
  static const double xs = 6;
  static const double s = 8;
  static const double m = 12;
  static const double card = 14; // widget inner padding
  static const double l = 16;
  static const double screen = 18; // screen horizontal padding
}

abstract final class AppRadius {
  static const double control = 8; // buttons
  static const double field = 12; // fields, rows, metrics, tabs
  static const double card = 24; // home screen widgets
}
